// Generates scripts/seed.sql from the old mock JSON in scripts/seed-data/.
// Usage (inside capyfolio/): node scripts/generate-seed.mjs
// Run the output once against the Supabase project (SQL editor or MCP execute_sql).
// Every row is marked is_sample = true. Old string ids map to deterministic uuids (md5 of "capyfolio:<id>").
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const load = (name) => JSON.parse(readFileSync(join(here, 'seed-data', name), 'utf8'));

const users = load('users.json');
const projects = load('projects.json');
const events = load('events.json');
const posts = load('posts.json');

/** Old string ids that must not be seeded (test account with a password). */
const SKIP_USERS = new Set(['u-test']);
/** Dev-only asset paths replaced by files served from public/. */
const AVATAR_OVERRIDES = { u_arthur: '/sample-avatars/artur.png' };

const uuid = (oldId) => {
  const h = createHash('md5').update(`capyfolio:${oldId}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-${((parseInt(h[16], 16) & 0x3) | 0x8).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`;
};

const q = (value) => (value === null || value === undefined || value === '' ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const id = (oldId) => (oldId ? `'${uuid(oldId)}'` : 'null');
const arr = (values) => (values && values.length ? `array[${values.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const json = (value) => `${q(JSON.stringify(value ?? []))}::jsonb`;
const int = (value) => String(Number.isFinite(value) ? Math.trunc(value) : 0);

const MONTHS = { jan: 1, fev: 2, mar: 3, abr: 4, mai: 5, jun: 6, jul: 7, ago: 8, set: 9, out: 10, nov: 11, dez: 12 };
const pad = (n) => String(n).padStart(2, '0');

/** "28 abr. 2025" -> "2025-04-28" */
const parseDate = (text) => {
  const m = /^(\d{1,2}) (\w{3})\.? (\d{4})/.exec(text.trim());
  if (!m) throw new Error(`Unparseable date: ${text}`);
  return `${m[3]}-${pad(MONTHS[m[2].toLowerCase()])}-${pad(Number(m[1]))}`;
};

/** "15 mai. 2025, 14:00 - 18:00" -> timestamptz literals in America/Sao_Paulo */
const parseEventRange = (text) => {
  const day = parseDate(text);
  const m = /(\d{2}:\d{2})\s*-\s*(\d{2}:\d{2})/.exec(text);
  if (!m) throw new Error(`Unparseable time range: ${text}`);
  const at = (time) => `(timestamp '${day} ${time}' at time zone 'America/Sao_Paulo')`;
  return { starts: at(m[1]), ends: at(m[2]) };
};

/** Display strings in the mock data -> an interval before now(). */
const RELATIVE = { 'Há 1 hora': '1 hour', 'Há 3 horas': '3 hours', 'Há 6 horas': '6 hours', Ontem: '1 day 2 hours' };
const ago = (label) => {
  const interval = RELATIVE[label];
  if (!interval) throw new Error(`Unknown relative timestamp: ${label}`);
  return `now() - interval '${interval}'`;
};

const out = [];
out.push('-- Generated by scripts/generate-seed.mjs. Sample content only (is_sample = true).');
out.push('begin;');

// Profiles: students, then organizations referenced by posts.
const seededUsers = users.filter((u) => !SKIP_USERS.has(u.id));
for (const u of seededUsers) {
  out.push(
    `insert into public.profiles (id, is_sample, name, role, focus, institution, short_institution, course, period, location, bio, tags, badges, avatar_url, github, linkedin, lattes, connections_base, profile_layout) values (` +
      [
        id(u.id), 'true', q(u.name), q(u.role), q(u.focus), q(u.institution), q(u.shortInstitution), q(u.course), q(u.period),
        q(u.location), q(u.bio), arr(u.tags), arr(u.badges), q(AVATAR_OVERRIDES[u.id] ?? u.avatar), q(u.github), q(u.linkedin),
        q(u.lattes), int(u.connections), u.profileLayout ? `${q(JSON.stringify(u.profileLayout))}::jsonb` : 'null',
      ].join(', ') +
      ') on conflict (id) do nothing;',
  );
}

const knownUsers = new Set(seededUsers.map((u) => u.id));
const orgs = new Map();
for (const p of posts) {
  if (p.isOrganization && !knownUsers.has(p.authorId) && !orgs.has(p.authorId)) orgs.set(p.authorId, p);
}
for (const [orgId, p] of orgs) {
  out.push(
    `insert into public.profiles (id, is_sample, is_organization, name, role, focus, institution, avatar_url) values (` +
      [id(orgId), 'true', 'true', q(p.authorName), q(p.authorRole), q(''), q(p.authorInstitution), q(p.authorAvatar)].join(', ') +
      ') on conflict (id) do nothing;',
  );
}

// Projects and authors.
for (const p of projects) {
  const creator = p.authorIds.find((a) => knownUsers.has(a));
  out.push(
    `insert into public.projects (id, created_by, is_sample, title, short_description, summary, key_results, methodology, files, institution, area, type, status, project_date, period, tags, url, visual_type, media_url, favorites_base) values (` +
      [
        id(p.id), id(creator), 'true', q(p.title), q(p.shortDescription), q(p.summary), arr(p.keyResults), q(p.methodology),
        json(p.files), q(p.institution), q(p.area), q(p.type), q(p.status), `date '${parseDate(p.date)}'`, q(p.period),
        arr(p.tags), q(p.url), q(p.visualType ?? 'standard'), q(p.media), int(p.favorites),
      ].join(', ') +
      ') on conflict (id) do nothing;',
  );
  p.authorIds
    .filter((a) => knownUsers.has(a))
    .forEach((a, position) => {
      out.push(`insert into public.project_authors (project_id, profile_id, position) values (${id(p.id)}, ${id(a)}, ${position}) on conflict do nothing;`);
    });
}

// Featured projects (after projects exist).
for (const u of seededUsers) {
  if (u.featuredProjectId && projects.some((p) => p.id === u.featuredProjectId)) {
    out.push(`update public.profiles set featured_project_id = ${id(u.featuredProjectId)} where id = ${id(u.id)};`);
  }
}

// Events.
for (const e of events) {
  const { starts, ends } = parseEventRange(e.date);
  out.push(
    `insert into public.events (id, is_sample, title, category, status, starts_at, ends_at, location, city, organizer, modality, tags, short_description, about_text, speakers, schedule, attendees_base) values (` +
      [
        id(e.id), 'true', q(e.title), q(e.category), q(e.status), starts, ends, q(e.location), q(e.city), q(e.organizer),
        q(e.modality), arr(e.tags), q(e.shortDescription), q(e.aboutText), json(e.speakers), json(e.schedule), int(e.attendeesCount),
      ].join(', ') +
      ') on conflict (id) do nothing;',
  );
}

// Posts and their sample comments (author snapshot only, no author_id).
for (const p of posts) {
  out.push(
    `insert into public.posts (id, author_id, is_sample, category, content, related_project_id, related_event_id, likes_base, created_at) values (` +
      [id(p.id), id(p.authorId), 'true', q(p.category), q(p.content), id(p.relatedProjectId), id(p.relatedEventId), int(p.likes), ago(p.timestamp)].join(', ') +
      ') on conflict (id) do nothing;',
  );
  for (const c of p.comments ?? []) {
    out.push(
      `insert into public.comments (id, post_id, author_id, author_name, author_institution, text, created_at) values (` +
        [id(c.id), id(p.id), 'null', q(c.authorName), q(c.authorInstitution), q(c.text), ago(c.timestamp)].join(', ') +
        ') on conflict (id) do nothing;',
    );
  }
}

out.push('commit;');
writeFileSync(join(here, 'seed.sql'), `${out.join('\n')}\n`, 'utf8');
console.log(`Wrote scripts/seed.sql (${out.length} statements)`);
